local Api = require("liseur_api")
local Fake = require("fake_http")

describe("liseur_api base URL", function()
    it("keeps a path prefix and drops default ports and trailing slashes", function()
        local b = Api.parseBase(" https://Books.Example.org:443/liseur/ ")
        assert.are.equal("https://books.example.org", b.origin)
        assert.are.equal("/liseur", b.prefix)
        assert.are.equal("https://books.example.org/liseur", b.url)
    end)

    it("refuses plain http except for this device", function()
        assert.is_nil((Api.parseBase("http://books.example.org")))
        assert.is_not_nil((Api.parseBase("http://localhost:8080")))
        assert.is_not_nil((Api.parseBase("http://127.0.0.1:8080/x")))
    end)

    it("refuses credentials, queries, fragments and odd paths", function()
        assert.is_nil((Api.parseBase("https://user:pw@books.example.org")))
        assert.is_nil((Api.parseBase("https://books.example.org/?x=1")))
        assert.is_nil((Api.parseBase("https://books.example.org/#a")))
        assert.is_nil((Api.parseBase("https://books.example.org/a/../b")))
        assert.is_nil((Api.parseBase("ftp://books.example.org")))
        assert.is_nil((Api.parseBase("https://books.example.org:99999")))
    end)

    it("keeps different servers, prefixes and accounts apart", function()
        local a = Api.parseBase("https://h.example/a")
        local b = Api.parseBase("https://h.example/b")
        assert.truthy(Api.namespace(a, "u1") ~= Api.namespace(b, "u1"))
        assert.truthy(Api.namespace(a, "u1") ~= Api.namespace(a, "u2"))
        assert.matches("^[%w_%-]+$", Api.namespace(a, "../../etc"))
        local function ns(url) return Api.namespace(Api.parseBase(url), "u1") end
        assert.truthy(ns("https://h.example/a/b") ~= ns("https://h.example/a_b"))
        assert.truthy(ns("http://localhost:8080") ~= ns("https://localhost:8080"))
        assert.truthy(ns("https://h.example/A"):lower() ~= ns("https://h.example/a"):lower())
        assert.matches("^[%l%d_%-]+$", ns("https://h.example/Some/Prefix"))
        assert.truthy(Api.namespace(a, "u1-x") ~= Api.namespace(Api.parseBase("https://h.example/a--u1"), "x"))
    end)

    it("joins paths under the prefix and escapes ids and queries", function()
        local api = Api.new{ base = Api.parseBase("https://h.example/p"), transport = function() end }
        assert.are.equal("https://h.example/p/v1/books/a%2Fb", api:url("/v1/books/" .. Api.escape("a/b")))
        assert.are.equal("https://h.example/p/v1/changes?limit=500&since=3", api:url("/v1/changes", { since = 3, limit = 500 }))
        assert.is_true(api:sameOrigin("https://h.example/other"))
        assert.is_false(api:sameOrigin("https://evil.example/p"))
        assert.is_false(api:sameOrigin("http://h.example/p"))
    end)
end)

describe("liseur_api requests", function()
    local fake, api
    before_each(function()
        fake = Fake.new()
        api = Api.new{ base = Api.parseBase("https://h.example/p"), token = "secret", transport = fake.transport }
    end)

    it("sends the bearer token and decodes JSON", function()
        fake:respond(200, { account_id = "u" })
        local data = api:get("/v1/token")
        assert.are.equal("u", data.account_id)
        assert.are.equal("Bearer secret", fake:last().headers.Authorization)
    end)

    it("sends a raw body byte for byte", function()
        fake:respond(200, { results = {} })
        api:postRaw("/v1/ops", '{"ops":[{"b":1,"a":2}]}')
        assert.are.equal('{"ops":[{"b":1,"a":2}]}', fake:last().body)
    end)

    it("classifies statuses and keeps route codes", function()
        fake:respond(401, { error = "invalid token" })
        local _, e = api:get("/v1/token")
        assert.are.equal("auth", e.kind)
        fake:respond(403, { error = "insufficient scope" })
        _, e = api:get("/v1/token")
        assert.are.equal("forbidden", e.kind)
        fake:respond(429, { error = "busy" }, { ["retry-after"] = "7" })
        _, e = api:get("/v1/token")
        assert.are.equal("rate_limited", e.kind)
        assert.are.equal(7, e.retry_after)
        assert.is_true(Api.retryable(e))
        fake:respond(400, { error = "op x: unknown work", code = "unknown_work" })
        _, e = api:get("/v1/token")
        assert.are.equal("refused", e.kind)
        assert.are.equal("unknown_work", e.code)
        assert.is_false(Api.retryable(e))
        fake:respond(410, { error = "resync_required" })
        _, e = api:get("/v1/changes")
        assert.are.equal("gone", e.kind)
    end)

    it("never follows a redirect", function()
        fake:respond(302, "", { location = "https://evil.example/" })
        local _, e = api:get("/v1/token")
        assert.are.equal("redirect", e.kind)
        assert.are.equal(1, #fake.requests)
    end)

    it("treats a network failure as an unknown outcome, not a rejection", function()
        fake:respond(nil, "timeout")
        local _, e = api:post("/v1/ops", { ops = {} })
        assert.are.equal("transport", e.kind)
        assert.is_true(e.unknown_outcome)
        assert.is_true(Api.retryable(e))
    end)

    it("refuses a success answer that is not JSON", function()
        fake:respond(200, "<html>proxy login</html>")
        local _, e = api:get("/v1/token")
        assert.are.equal("malformed", e.kind)
    end)

    it("backs off with a bounded, jittered delay", function()
        assert.are.equal(15, Api.backoff(1, function() return 1 end))
        assert.are.equal(7.5, Api.backoff(1, function() return 0 end))
        assert.are.equal(1800, Api.backoff(30, function() return 1 end))
    end)
end)
